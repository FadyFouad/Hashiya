package com.etatech.hashiya.core.importer

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class BibTeXParserTest {
    private fun parse(text: String) = BibTeXParser.parse(text)

    private fun single(text: String): ImportedEntry = parse(text).entries.single()

    private fun authorsOf(author: String): List<String> = single("@misc{k, title = {T}, author = {$author}}").authors

    @Test
    fun `an entry gives its type lowercased, key and line`() {
        val entry = single("\n\n@ARTICLE{Key2020,\n  TITLE = {A title}\n}")
        assertEquals(3, entry.line)
        assertEquals("article", entry.entryType)
        assertEquals("Key2020", entry.citeKey)
        assertEquals("A title", entry.title)
    }

    @Test
    fun `text before the first entry and comment and preamble entries are ignored`() {
        val result = parse(
            "Generated by Mendeley\n@comment{x = {y}}\n@preamble{ \"\\newcommand{\\a}{b}\" }\n@misc{k, title = {T}}"
        )
        assertEquals(listOf("k"), result.entries.map { it.citeKey })
        assertEquals(emptyList<ImportIssue>(), result.issues)
    }

    @Test
    fun `string macros, concatenation, parentheses and month macros`() {
        val entry = single(
            """
            @string{ a = "Journal of " }
            @STRING(b = {Machine {L}earning})
            @string{ c = a # b }
            @article{k, title = "T", journal = c # " " # jan}
            """.trimIndent()
        )
        assertEquals("Journal of Machine Learning January", entry.venue)
    }

    @Test
    fun `an unknown macro expands to nothing`() {
        assertEquals("X", single("@article{k, title = {T}, journal = nope # {X}}").venue)
    }

    @Test
    fun `numbers, quoted values with braces and a trailing comma`() {
        val entry = single("@article{k, title = \"A {\"}quoted{\"} title\", year = 2019, volume = 7,}")
        assertEquals("A \"quoted\" title", entry.title)
        assertEquals(2019, entry.year)
        assertEquals("7", entry.volume)
    }

    @Test
    fun `an entry written in parentheses`() {
        assertEquals("T", single("@article(k,\n title = {T}\n)").title)
    }

    @Test
    fun `an entry without a key`() {
        val entry = single("@misc{title = {T}}")
        assertNull(entry.citeKey)
        assertEquals("T", entry.title)
    }

    @Test
    fun `an entry missing its closing brace is reported and the next one still parses`() {
        val result = parse(
            "@article{bad,\n  title = {Never closed,\n  year = {2019},\n\n@article{good,\n  title = {Fine}\n}\n"
        )
        assertEquals(listOf(ImportIssue(1, ImportIssueKind.Malformed)), result.issues)
        assertEquals(listOf("good"), result.entries.map { it.citeKey })
        assertEquals(5, result.entries.single().line)
    }

    @Test
    fun `a syntax error is reported at the entry's line`() {
        val result = parse("@misc{a, title = {A}}\n@article{bad, title {missing equals}}\n@misc{c, title = {C}}")
        assertEquals(listOf(ImportIssue(2, ImportIssueKind.Malformed)), result.issues)
        assertEquals(listOf("a", "c"), result.entries.map { it.citeKey })
    }

    @Test
    fun `an entry with neither title nor DOI is reported as empty`() {
        val result = parse("@article{k, note = {nothing}}")
        assertEquals(listOf(ImportIssue(1, ImportIssueKind.Empty)), result.issues)
        assertEquals(emptyList<ImportedEntry>(), result.entries)
    }

    @Test
    fun `an entry with a DOI but no title is kept`() {
        assertEquals("10.1/x", single("@article{k, doi = {10.1/x}}").doi)
    }

    @Test
    fun `name forms`() {
        assertEquals(
            listOf("Yann LeCun", "Ludwig van Beethoven", "John Smith Jr.", "Ada Lovelace"),
            authorsOf(
                "LeCun, Yann and van Beethoven, Ludwig and Smith, Jr., John and Ada Lovelace"
            )
        )
    }

    @Test
    fun `corporate names stay whole, commas and and included`() {
        assertEquals(listOf("Barnes and Noble, Inc.", "Jane Doe"), authorsOf("{Barnes and Noble, Inc.} and Doe, Jane"))
    }

    @Test
    fun `and splits only outside braces and only as a word, in any case`() {
        assertEquals(listOf("A Anderson", "B Band"), authorsOf("Anderson, A AND Band, B"))
        assertEquals(listOf("Tom and Jerry"), authorsOf("Tom {and} Jerry"))
    }

    @Test
    fun `others is dropped`() {
        assertEquals(listOf("Ashish Vaswani"), authorsOf("Vaswani, Ashish and others"))
    }

    @Test
    fun `the BibLaTeX extended name form`() {
        assertEquals(listOf("Anja von der Linde"), authorsOf("family=Linde, given=Anja, prefix=von der, useprefix=true"))
        assertEquals(listOf("Martin Luther King Jr."), authorsOf("family=King, given=Martin Luther, suffix=Jr."))
    }

    @Test
    fun `names are decoded after splitting`() {
        assertEquals(listOf("Kurt Gödel", "Paul Erdős"), authorsOf("G{\\\"o}del, Kurt and Erd\\H{o}s, Paul"))
    }

    @Test
    fun `editors stand in when there are no authors`() {
        assertEquals(listOf("Jan Berg"), single("@book{k, title = {T}, editor = {Berg, Jan}}").authors)
        assertEquals(
            listOf("A Author"),
            single("@book{k, title = {T}, author = {Author, A}, editor = {Berg, Jan}}").authors
        )
    }

    @Test
    fun `year from year, else from date`() {
        assertEquals(2016, single("@article{k, title = {T}, date = {2016-06}}").year)
        assertEquals(2015, single("@article{k, title = {T}, year = {2015}, date = {2016-06}}").year)
    }

    @Test
    fun `venue fallbacks`() {
        assertEquals("J", single("@article{k, title = {T}, journal = {J}, booktitle = {B}}").venue)
        assertEquals("JT", single("@article{k, title = {T}, journaltitle = {JT}}").venue)
        assertEquals("B", single("@inproceedings{k, title = {T}, booktitle = {B}}").venue)
        assertEquals("S", single("@phdthesis{k, title = {T}, school = {S}}").venue)
        assertEquals("I", single("@techreport{k, title = {T}, institution = {I}}").venue)
        assertEquals("Self-published", single("@misc{k, title = {T}, howpublished = {Self-published}}").venue)
        assertNull(single("@misc{k, title = {T}, howpublished = {\\url{https://x.org}}}").venue)
    }

    @Test
    fun `url from url, else from howpublished`() {
        assertEquals("https://x.org/a_b", single("@misc{k, title = {T}, url = {https://x.org/a\\_b}}").url)
        assertEquals("https://x.org", single("@misc{k, title = {T}, howpublished = {\\url{https://x.org}}}").url)
        assertEquals("http://x.org", single("@misc{k, title = {T}, howpublished = {http://x.org}}").url)
    }

    @Test
    fun `number else issue, and pages`() {
        val entry = single("@article{k, title = {T}, issue = {4}, pages = {770--778}}")
        assertEquals("4", entry.issue)
        assertEquals("770", entry.firstPage)
        assertEquals("778", entry.lastPage)
        assertEquals("3", single("@article{k, title = {T}, number = {3}, issue = {4}}").issue)
    }

    @Test
    fun `DOI order - doi field, arXiv eprint, url, Google Scholar journal`() {
        assertEquals("10.1/a", single("@article{k, doi = {10.1/A}, eprint = {1706.03762}, archiveprefix = {arXiv}}").doi)
        assertEquals("10.48550/arxiv.1706.03762", single("@misc{k, title = {T}, eprint = {1706.03762v5}, eprinttype = {arxiv}}").doi)
        assertEquals("10.48550/arxiv.1810.04805", single("@article{k, title = {T}, arxivId = {1810.04805}}").doi)
        assertNull(single("@misc{k, title = {T}, eprint = {12345}, eprinttype = {pubmed}}").doi)
        assertEquals("10.1093/x", single("@article{k, title = {T}, url = {https://doi.org/10.1093/X}}").doi)
        assertEquals("10.48550/arxiv.1412.6980", single("@article{k, title = {T}, url = {http://arxiv.org/abs/1412.6980v9}}").doi)
        assertEquals("10.48550/arxiv.1810.04805", single("@article{k, title = {T}, journal = {arXiv preprint arXiv:1810.04805}}").doi)
    }

    @Test
    fun `entry types map to OpenAlex's work and source types`() {
        fun kinds(type: String) = single("@$type{k, title = {T}}").let { it.workType to it.sourceType }
        assertEquals("article" to "journal", kinds("article"))
        assertEquals("article" to "conference", kinds("inproceedings"))
        assertEquals("article" to "conference", kinds("conference"))
        assertEquals("book" to null, kinds("book"))
        assertEquals("book" to null, kinds("proceedings"))
        assertEquals("book-chapter" to null, kinds("incollection"))
        assertEquals("book-chapter" to null, kinds("inbook"))
        assertEquals("dissertation" to null, kinds("phdthesis"))
        assertEquals("dissertation" to null, kinds("mastersthesis"))
        assertEquals("report" to null, kinds("techreport"))
        assertEquals(null to null, kinds("misc"))
        assertEquals(null to null, kinds("online"))
    }

    @Test
    fun `arXiv papers become preprints only when the type says nothing or the journal is an arXiv preprint`() {
        val misc = single("@misc{k, title = {T}, doi = {10.48550/arXiv.1706.03762}}")
        assertEquals("preprint" to "repository", misc.workType to misc.sourceType)
        val scholar = single("@article{k, title = {T}, journal = {arXiv preprint arXiv:1706.03762}}")
        assertEquals("preprint" to "repository", scholar.workType to scholar.sourceType)
        val published = single("@article{k, title = {T}, journal = {NAACL}, eprint = {1810.04805}, archivePrefix = {arXiv}}")
        assertEquals("article" to "journal", published.workType to published.sourceType)
    }
}
